let currentLang = "uk";

function applyLang(lang) {
   currentLang = lang;
   const t = i18n[lang];
   document.querySelectorAll("[data-i18n]").forEach((el) => {
      const k = el.dataset.i18n;
      if (t[k] !== undefined) el.textContent = t[k];
   });
   // lang button label
   document.getElementById("langMainBtn").textContent = t.lang_label;
   // active states
   document
      .querySelectorAll(".lang-opt")
      .forEach((b) => b.classList.toggle("active", b.dataset.lang === lang));
   document
      .querySelectorAll(".mobile-lang-btn")
      .forEach((b) => b.classList.toggle("active", b.dataset.lang === lang));
   // retrigger slider to update text
   sliderRender();
}

// ─── CURSOR ─────────────────────────────────────────────────────────────────
const cursor = document.getElementById("cursor");
const ring = document.getElementById("cursorRing");
let mx = 0,
   my = 0,
   rx = 0,
   ry = 0;
document.addEventListener("mousemove", (e) => {
   mx = e.clientX;
   my = e.clientY;
   cursor.style.left = mx + "px";
   cursor.style.top = my + "px";
});
(function animRing() {
   rx += (mx - rx) * 0.14;
   ry += (my - ry) * 0.14;
   ring.style.left = rx + "px";
   ring.style.top = ry + "px";
   requestAnimationFrame(animRing);
})();
document
   .querySelectorAll("a,button,.service-card,.review-card,.step")
   .forEach((el) => {
      el.addEventListener("mouseenter", () => {
         cursor.classList.add("hover");
         ring.classList.add("hover");
      });
      el.addEventListener("mouseleave", () => {
         cursor.classList.remove("hover");
         ring.classList.remove("hover");
      });
   });

